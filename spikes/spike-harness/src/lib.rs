//! M0 spike 共用的底座：实验记录、帧耗时/CPU/RSS 采样、GL 截图。
//!
//! 这三样和「验的是播放还是界面」无关，但**每一个 spike 都要有**：
//! 没有记录，跑没跑过只有跑的人自己知道；没有分位数，帧率的平均值会把
//! 卡顿平均掉；没有截图，「层级对不对、画面糊不糊」只能靠一句断言。
//!
//! 它原先长在 `slint-mpv` 里（SPIKE-001 / SPIKE-002）。SPIKE-003（issue
//! #10）要在另一个窗口里量同样的东西，于是把这三个模块抽出来共用，而不是
//! 复制一份——两份记录格式一旦分叉，跨平台的记录就没法逐行对照了，那正是
//! 这套模板存在的理由。
//!
//! **不要往这里加业务**。它只认「怎么把证据写出来」，不认 mpv、不认评论、
//! 也不认任何一个具体 spike 的场景。

